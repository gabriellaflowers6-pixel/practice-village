// AI coach endpoint for the deployed Moxie Studios site. Mirrors serve.py's
// /coach contract exactly: same request {messages}, same {ok, reply, lesson}
// response, same 32-pose lesson filtering. Calls Gemini (gemini-2.5-flash)
// through Vertex AI express mode so the key stays server-side and the Google
// Cloud + Gemini hackathon gates are both satisfied. Env: GEMINI_API_KEY
// (required; a Vertex express-mode key), optional GEMINI_MODEL override.
// coach-lib.mjs here is a committed copy of mockups/coach-lib.mjs (build.sh
// guards that they stay identical). coach-prompt.mjs is generated by
